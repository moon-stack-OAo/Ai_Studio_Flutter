String _hash(String value) => sha256.convert(utf8.encode(value)).toString();

class _InvalidHistoryBytes implements Exception {
  const _InvalidHistoryBytes(this.bytes);
  final List<int> bytes;
}

class _InvalidHistory implements Exception {
  const _InvalidHistory();
}

/// Injectable operations for deterministic interruption/read-back tests.
/// Paths are generated by this store, never taken from a snapshot.
class HistoryFileAccess {
  const HistoryFileAccess();

  bool _missing(FileSystemException error) =>
      [2, 3].contains(error.osError?.errorCode);

  Future<void> _checkParents(String path) async {
    var current = File(path).absolute.path;
    while (true) {
      final type = await FileSystemEntity.type(current, followLinks: false);
      if (type == FileSystemEntityType.link) {
        throw FileSystemException('Unsafe history path');
      }
      final parent = File(current).parent.path;
      if (parent == current) return;
      current = parent;
    }
  }

  Future<String?> read(String path) async {
    await _checkParents(path);
    try {
      final bytes = await File(path).readAsBytes();
      try {
        return utf8.decode(bytes);
      } on FormatException {
        throw _InvalidHistoryBytes(bytes);
      }
    } on FileSystemException catch (error) {
      if (_missing(error)) return null;
      rethrow;
    }
  }

  Future<void> write(String path, String value) async {
    await _checkParents(path);
    await Directory(File(path).parent.path).create(recursive: true);
    await _checkParents(path);
    final type = await FileSystemEntity.type(path, followLinks: false);
    if (type != FileSystemEntityType.notFound &&
        type != FileSystemEntityType.file) {
      throw const HistoryStorageException();
    }
    await File(path).writeAsString(value, flush: true);
  }

  Future<void> remove(String path) async {
    await _checkParents(path);
    try {
      await File(path).delete();
    } on FileSystemException catch (error) {
      if (!_missing(error)) rethrow;
    }
  }

  Future<List<String>> files(String path) async {
    await _checkParents(path);
    final result = <String>[];
    // No recursive traversal: all managed files live directly in this directory.
    try {
      await for (final entity in Directory(path).list(followLinks: false)) {
        if (await FileSystemEntity.type(entity.path, followLinks: false) !=
            FileSystemEntityType.file) {
          throw const HistoryStorageException();
        }
        result.add(entity.path);
      }
    } on FileSystemException catch (error) {
      if (!_missing(error)) rethrow;
    }
    return result;
  }
}

Future<Directory> _defaultRoot() async =>
    historyRootFromApplicationSupport(await getApplicationSupportDirectory());

@visibleForTesting
Future<Directory> historyRootFromApplicationSupport(Directory support) async {
  // The OS-provided app container is trusted and can have system aliases
  // (iOS /var -> /private/var). Resolve only that ancestor, not history_v2 or
  // its children: links inside our managed storage must still be rejected.
  final canonicalSupport = await support.resolveSymbolicLinks();
  return Directory('$canonicalSupport/history_v2');
}

/// Small manifests reference immutable, content-addressed per-session revisions.
/// The pending journal is authoritative once published, including deletions.
/// This is a recoverable protocol, not an atomic multi-file/fsync guarantee.
class FileHistorySnapshotStore<T> implements RecoverableHistoryStorage<T> {
  FileHistorySnapshotStore({
    required this.scope,
    required this.legacyKey,
    required this.legacyLoad,
    required this.decode,
    required this.encode,
    required this.empty,
    Future<Directory> Function()? root,
    Future<SharedPreferences> Function()? prefs,
    this.files = const HistoryFileAccess(),
  }) : _rootProvider = root ?? _defaultRoot,
       _prefsProvider = prefs ?? SharedPreferences.getInstance;

  final String scope;
  final String legacyKey;
  final Future<T> Function() legacyLoad;
  final T Function(String) decode;
  final Future<String> Function(T) encode;
  final T empty;
  final HistoryFileAccess files;
  final Future<Directory> Function() _rootProvider;
  final Future<SharedPreferences> Function() _prefsProvider;
  String? _root;
  // Shared per-scope queue also serializes accidentally duplicated instances.
  static final Map<String, Future<void>> _queues = {};
  @override
  HistoryRecoveryState recoveryState = HistoryRecoveryState.healthy;
  @override
  bool writesBlocked = true;

  Future<R> _serial<R>(Future<R> Function() action) async {
    final directory = (await _rootProvider()).absolute;
    final normalized = directory.uri.normalizePath().toFilePath();
    final root =
        '${normalized.replaceAll(String.fromCharCode(92), '/')}/${_hash(scope)}';
    _root = root;
    // Windows paths are case-insensitive; separators and dot segments must not
    // create independent queues for the same directory. Cross-process writers
    // are not supported (the apps own one storage instance per scope).
    final queueKey = Platform.isWindows ? root.toLowerCase() : root;
    final previous = _queues[queueKey] ?? Future<void>.value();
    final result = previous.then((_) => action());
    final tail = result.then<void>(
      (_) {},
      onError: (Object _, StackTrace _) {},
    );
    _queues[queueKey] = tail;
    try {
      return await result;
    } finally {
      if (identical(_queues[queueKey], tail)) _queues.remove(queueKey);
    }
  }

  String _path(String name) => '$_root/$name';
  final _invalidBytes = <String, List<int>>{};
  Future<String?> _read(String name) async {
    try {
      final raw = await files.read(_path(name));
      _invalidBytes.remove(name);
      return raw;
    } on _InvalidHistoryBytes catch (error) {
      _invalidBytes[name] = error.bytes;
      return '\u0000'; // Invalid JSON; exact bytes are retained by _isolate.
    }
  }

  Future<void> _remove(String name) => files.remove(_path(name));
  Future<void> _put(String name, String value) async {
    await files.write(_path(name), value);
    if (await _read(name) != value) throw const HistoryStorageException();
  }

  Future<void> _immutable(String name, String value) async {
    final old = await _read(name);
    if (old != null) {
      if (old != value) {
        recoveryState = HistoryRecoveryState.damaged;
        await _isolate(name, old);
        throw const HistoryStorageException();
      }
      return;
    }
    await _put(name, value);
  }

  Future<void> _isolate(String name, String raw) async {
    final slot = 'quarantine/${_hash(name)}.json';
    final bytes = _invalidBytes[name];
    final preserved = jsonEncode(
      bytes == null
          ? {'encoding': 'utf8', 'text': raw}
          : {'encoding': 'base64', 'bytes': base64Encode(bytes)},
    );
    final old = await _read(slot);
    if (old != null && old != preserved) throw const HistoryStorageException();
    if (old == null) await _put(slot, preserved);
  }

  bool _digest(Object? value) =>
      value is String && RegExp(r'^[a-f0-9]{64}$').hasMatch(value);

  Future<Map<String, dynamic>> _manifest(String digest) async {
    if (!_digest(digest)) throw const _InvalidHistory();
    final name = 'manifests/$digest.json';
    final raw = await _read(name);
    if (raw == null) throw const _InvalidHistory();
    try {
      if (_hash(raw) != digest) throw const HistoryStorageException();
      final manifest = jsonDecode(raw);
      if (manifest is! Map<String, dynamic> ||
          manifest['schema'] != 1 ||
          manifest['refs'] is! List) {
        throw const HistoryStorageException();
      }
      final ids = <String>{};
      for (final ref in manifest['refs'] as List) {
        if (ref is! Map ||
            ref['id'] is! String ||
            (ref['id'] as String).isEmpty ||
            !ids.add(ref['id'] as String) ||
            !_digest(ref['revision'])) {
          throw const HistoryStorageException();
        }
      }
      return manifest;
    } catch (_) {
      recoveryState = HistoryRecoveryState.damaged;
      await _isolate(name, raw);
      throw const _InvalidHistory();
    }
  }

  Future<String> _snapshot(String digest, String active) async {
    final manifest = await _manifest(digest);
    final sessions = <Object>[];
    var rawSize = 0;
    for (final ref in manifest['refs'] as List) {
      final name =
          'sessions/${_hash(ref['id'] as String)}-${ref['revision']}.json';
      final raw = await _read(name);
      if (raw == null) throw const _InvalidHistory();
      try {
        if (_hash(raw) != ref['revision']) {
          throw const HistoryStorageException();
        }
        final row = jsonDecode(raw);
        if (row is! Map || row['id'] != ref['id']) {
          throw const HistoryStorageException();
        }
        decode(
          jsonEncode({
            'sessions': [row],
            'activeId': ref['id'],
          }),
        );
        sessions.add(row);
        rawSize += raw.length;
      } catch (_) {
        recoveryState = HistoryRecoveryState.damaged;
        await _isolate(name, raw);
        throw const _InvalidHistory();
      }
    }
    // Validates every row before the existing bounded model decoder is invoked.
    final input = (sessions, active, decode);
    return rawSize >= _workerThreshold
        ? compute(_assembleSnapshot<T>, input)
        : _assembleSnapshot<T>(input);
  }

  Future<(String, String)> _stage(String payload) async {
    final input = (payload, decode);
    // Only pure CPU/model work crosses isolates. IO, read-back, quarantine and
    // publication stay ordered on the owning isolate; small histories avoid spawn.
    final (active, encoded) = payload.length >= _workerThreshold
        ? await compute(_prepareSnapshot<T>, input)
        : _prepareSnapshot<T>(input);
    final refs = <Object>[];
    for (final row in encoded) {
      final id = row['id']!;
      final raw = row['raw']!;
      final revision = row['revision']!;
      await _immutable('sessions/${_hash(id)}-$revision.json', raw);
      refs.add({'id': id, 'revision': revision});
    }
    final manifest = jsonEncode({'schema': 1, 'refs': refs});
    final digest = _hash(manifest);
    await _immutable('manifests/$digest.json', manifest);
    await _snapshot(digest, active);
    return (digest, active);
  }

  Future<void> _finishPending() async {
    final raw = await _read('pending.json');
    if (raw == null) return;
    Map<String, dynamic> pending;
    try {
      pending = jsonDecode(raw) as Map<String, dynamic>;
      if (!_digest(pending['target']) ||
          (pending['previous'] != '' && !_digest(pending['previous'])) ||
          pending['active'] is! String) {
        throw const HistoryStorageException();
      }
      await _snapshot(pending['target'] as String, pending['active'] as String);
    } catch (_) {
      await _isolate('pending.json', raw);
      throw const HistoryStorageException();
    }
    // Journal first: if any following write tears, restart completes this target.
    if (pending['previous'] == '') {
      await _remove('previous');
    } else {
      await _put('previous', pending['previous'] as String);
    }
    await _put('commit', pending['target'] as String);
    await _put('active.json', jsonEncode(pending['active']));
    await _remove('pending.json');
  }

  Future<void> _publish(
    String target,
    String active, {
    bool replace = false,
  }) async {
    final current = await _read('commit');
    if (!replace && current != null) await _snapshot(current, active);
    await _immutable(
      'pending.json',
      jsonEncode({
        'target': target,
        'previous': replace ? '' : current ?? '',
        'active': active,
      }),
    );
    await _finishPending();
  }

  Future<void> _legacyCleanup({bool clearOriginals = false}) async {
    final p = await _prefsProvider();
    // A failed legacy write may leave its optimistic cache ahead of disk.
    await p.reload();
    if (!clearOriginals &&
        (p.containsKey('$legacyKey.corrupt') ||
            p.containsKey('$legacyKey.previous.corrupt'))) {
      await _immutable('legacy-quarantine', '1');
    }
    for (final key in [
      legacyKey,
      '$legacyKey.previous',
      '$legacyKey.clearing',
      '$legacyKey.replacing',
      if (clearOriginals) '$legacyKey.corrupt',
      if (clearOriginals) '$legacyKey.previous.corrupt',
    ]) {
      if (p.containsKey(key) && (!await p.remove(key) || p.containsKey(key))) {
        try {
          await p.reload();
        } catch (_) {}
        throw const HistoryStorageException();
      }
    }
  }

  // Only called after the complete current snapshot has been validated. A
  // previous manifest is optional for GC, but IO/quarantine failures are not
  // corruption and must keep writes locked. Keep _gc itself fail-closed.
  Future<void> _retireInvalidPrevious() async {
    final previous = await _read('previous');
    if (previous == null) return;
    try {
      await _manifest(previous);
    } on _InvalidHistory {
      // _manifest already preserves any available damaged manifest bytes.
      // Preserve the pointer too (including invalid UTF8) before invalidating
      // it; _isolate refuses to overwrite a different immutable quarantine.
      await _isolate('previous', previous);
      await _remove('previous');
      if (await _read('previous') != null) {
        throw const HistoryStorageException();
      }
    }
  }

  Future<void> _gc() async {
    final keepManifests = <String>{};
    final keepSessions = <String>{};
    for (final pointer in ['commit', 'previous']) {
      final digest = await _read(pointer);
      if (digest == null) continue;
      final manifest = await _manifest(digest);
      keepManifests.add('$digest.json');
      for (final ref in manifest['refs'] as List) {
        keepSessions.add(
          '${_hash(ref['id'] as String)}-${ref['revision']}.json',
        );
      }
    }
    for (final entry in {
      'manifests': keepManifests,
      'sessions': keepSessions,
    }.entries) {
      for (final path in await files.files(_path(entry.key))) {
        final name = path
            .replaceAll(String.fromCharCode(92), '/')
            .split('/')
            .last;
        if (!entry.value.contains(name)) await files.remove(path);
      }
    }
  }

  Future<T> load() => _serial(_load);
  @override
  Future<T> recover() => load();

  Future<T> _load() async {
    writesBlocked = true;
    recoveryState = HistoryRecoveryState.readFailed;
    try {
      if (await _read('clearing') != null) {
        await _finishClear();
      }
      final initialized = await _read('initialized');
      if (initialized == null) {
        // Existing artifacts without the sentinel cannot authorize prefs fallback.
        if (await _read('pending.json') != null) {
          await _immutable('initialized', '1');
          await _finishPending();
        } else {
          for (final authority in [
            'commit',
            'previous',
            'active.json',
            'legacy-cleaned',
            'legacy-quarantine',
          ]) {
            if (await _read(authority) != null) {
              throw const HistoryStorageException();
            }
          }
          final snapshot = await legacyLoad();
          final payload = await encode(snapshot);
          final (target, active) = await _stage(payload);
          // Publishing the journal before initialized makes interrupted bootstrap
          // explicit; a journal alone is never treated as fresh/missing history.
          await _immutable(
            'pending.json',
            jsonEncode({'target': target, 'previous': '', 'active': active}),
          );
          await _immutable('initialized', '1');
        }
      } else if (initialized != '1') {
        await _isolate('initialized', initialized);
        throw const HistoryStorageException();
      }
      await _finishPending();
      if (await _read('legacy-cleaned') != '1') {
        await _legacyCleanup();
        await _immutable('legacy-cleaned', '1');
      }
      var current = await _read('commit');
      String payload;
      var recovered = false;
      try {
        if (current == null) throw const _InvalidHistory();
        payload = await _snapshot(current, '');
      } on _InvalidHistory {
        // A read/IO exception is not evidence of corruption; preserve originals.
        if (current != null) await _isolate('commit', current);
        final previous = await _read('previous');
        if (previous == null) rethrow;
        payload = await _snapshot(previous, '');
        await _put('commit', previous);
        current = previous;
        recovered = true;
      }
      var active = '';
      final rawActive = await _read('active.json');
      if (rawActive != null) {
        try {
          final value = jsonDecode(rawActive);
          if (value is! String) throw const HistoryStorageException();
          active = value;
        } catch (_) {
          await _isolate('active.json', rawActive);
          recovered = true;
        }
      }
      final input = (payload, active, decode);
      final snapshot = payload.length >= _workerThreshold
          ? await compute(_decodeActiveSnapshot<T>, input)
          : _decodeActiveSnapshot<T>(input);
      await _retireInvalidPrevious();
      await _gc();
      final quarantined =
          (await files.files(_path('quarantine'))).isNotEmpty ||
          await _read('legacy-quarantine') != null;
      writesBlocked = false;
      recoveryState = recovered || quarantined
          ? HistoryRecoveryState.recovered
          : HistoryRecoveryState.healthy;
      return snapshot;
    } catch (_) {
      throw const HistoryStorageException();
    }
  }

  Future<void> save(T snapshot) => _serial(() => _save(snapshot, false));
  @override
  Future<void> replaceHistory(T snapshot) =>
      _serial(() => _save(snapshot, true));

  Future<void> _save(T snapshot, bool replace) async {
    if (writesBlocked) throw const HistoryStorageException();
    try {
      await _finishPending();
      final payload = await encode(snapshot);
      final (target, active) = await _stage(payload);
      final current = await _read('commit');
      if (current == target && !replace) {
        await _put('active.json', jsonEncode(active));
      } else {
        await _publish(target, active, replace: replace);
      }
      await _gc();
    } catch (_) {
      writesBlocked = true;
      recoveryState = HistoryRecoveryState.readFailed;
      throw const HistoryStorageException();
    }
  }

  Future<void> _finishClear() async {
    // This marker can only be created by an explicitly confirmed clear request.
    // Explicit consent also authorizes replacing a damaged authority sentinel.
    await _put('initialized', '1');
    for (final name in ['previous', 'commit', 'pending.json', 'active.json']) {
      await _remove(name);
    }
    for (final dir in ['sessions', 'manifests', 'quarantine']) {
      for (final path in await files.files(_path(dir))) {
        await files.remove(path);
      }
    }
    await _legacyCleanup(clearOriginals: true);
    await _remove('legacy-quarantine');
    await _put('legacy-cleaned', '1');
    final payload = await encode(empty);
    final (target, _) = await _stage(payload);
    await _publish(target, '', replace: true);
    await _remove('clearing');
  }

  @override
  Future<void> clearHistory(T empty) => _serial(() async {
    writesBlocked = true;
    try {
      await _immutable('clearing', '1');
      await _finishClear();
      writesBlocked = false;
      recoveryState = HistoryRecoveryState.missing;
    } catch (_) {
      recoveryState = HistoryRecoveryState.readFailed;
      throw const HistoryStorageException();
    }
  });
}

const _workerThreshold = 64 * 1024;

(String, List<Map<String, String>>) _prepareSnapshot<T>(
  (String, T Function(String)) input,
) {
  try {
    final (payload, decode) = input;
    decode(payload);
    final root = jsonDecode(payload) as Map<String, dynamic>;
    final rows = <Map<String, String>>[];
    for (final row in root['sessions'] as List) {
      final raw = jsonEncode(row);
      rows.add({
        'id': (row as Map)['id'] as String,
        'raw': raw,
        'revision': _hash(raw),
      });
    }
    return (root['activeId'] as String? ?? '', rows);
  } catch (_) {
    // Never send a FormatException (whose source may contain private content).
    throw const HistoryStorageException();
  }
}

String _assembleSnapshot<T>((List<Object>, String, T Function(String)) input) {
  try {
    final (sessions, active, decode) = input;
    final payload = jsonEncode({'sessions': sessions, 'activeId': active});
    decode(payload);
    return payload;
  } catch (_) {
    throw const HistoryStorageException();
  }
}

T _decodeActiveSnapshot<T>((String, String, T Function(String)) input) {
  try {
    final (payload, requestedActive, decode) = input;
    final root = jsonDecode(payload) as Map<String, dynamic>;
    final sessions = root['sessions'] as List;
    var active = requestedActive;
    if (!sessions.any((s) => (s as Map)['id'] == active)) {
      active = sessions.isEmpty ? '' : (sessions.first as Map)['id'] as String;
    }
    root['activeId'] = active;
    return decode(jsonEncode(root));
  } catch (_) {
    throw const HistoryStorageException();
  }
}
